#!/usr/bin/env python3
"""Quantify overlap between the curated Saudi case reports and the Phenopacket Store.

Reviewer 1 asked what was done to ensure the published cases used for PAVS are
not duplicates of phenopackets generated by others. Within PAVS we already
collapse re-reported patients onto a single source PMID. This script measures
the residual overlap with the external GA4GH Phenopacket Store at the
publication (PMID) level: any Saudi case report (prefix M) whose source PMID
also appears in a Store phenopacket is reported, so it can be flagged with a
``dct:source`` cross-reference (or excluded) by downstream users.

It does NOT assert patient-level identity (the same publication can describe
many patients); it reports the publication-level overlap, which is the
reproducible, conservative upper bound on duplication.

Run:
    python evaluation/similarity/scripts/crosssource_pmid_overlap.py \
        --pavs data/PAVS_phenopackets.json \
        --store submodules/phenopackets-store/0.1.26
"""
import argparse
import json
import os
import re

PMID_RE = re.compile(r"PMID[:_ ]?(\d+)", re.I)


def pmids_from_packet(pp):
    out = set()
    for ref in pp.get("metaData", {}).get("externalReferences", []):
        blob = f"{ref.get('id', '')} {ref.get('reference', '')} {ref.get('description', '')}"
        out.update(PMID_RE.findall(blob))
    return out


def saudi_report_pmids(pavs_json):
    with open(pavs_json) as fh:
        packets = json.load(fh)
    case_pmids = {}
    for pp in packets:
        if pp["id"].startswith("PAVS:M"):          # Saudi literature case reports
            case_pmids[pp["id"]] = pmids_from_packet(pp)
    return case_pmids


def store_pmids(store_dir):
    pmids = set()
    n = 0
    for root, _, files in os.walk(store_dir):
        for f in files:
            if not f.endswith(".json"):
                continue
            try:
                with open(os.path.join(root, f)) as fh:
                    pmids |= pmids_from_packet(json.load(fh))
                    n += 1
            except Exception:
                continue
    return pmids, n


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pavs", default="data/PAVS_phenopackets.json")
    ap.add_argument("--store", required=True,
                    help="Directory of Phenopacket Store v0.1.26 JSON files")
    args = ap.parse_args()

    case_pmids = saudi_report_pmids(args.pavs)
    all_saudi_pmids = set().union(*case_pmids.values()) if case_pmids else set()
    spmids, n_store = store_pmids(args.store)

    overlapping_pmids = all_saudi_pmids & spmids
    overlapping_cases = [cid for cid, ps in case_pmids.items() if ps & spmids]

    print(f"Saudi case reports (prefix M): {len(case_pmids)}")
    print(f"  with >=1 source PMID:        {sum(1 for p in case_pmids.values() if p)}")
    print(f"  distinct source PMIDs:       {len(all_saudi_pmids)}")
    print(f"Store phenopackets scanned:    {n_store}  (distinct PMIDs: {len(spmids)})")
    print(f"\nOverlapping PMIDs:             {len(overlapping_pmids)}")
    print(f"Saudi case reports sharing a Store PMID: {len(overlapping_cases)} "
          f"({100*len(overlapping_cases)/max(1,len(case_pmids)):.1f}% of M cases)")
    if overlapping_pmids:
        print("PMIDs:", sorted(overlapping_pmids))


if __name__ == "__main__":
    main()
